"""Coordinate requests to two AI models for comparison."""

# Standard-library imports
import os
import logging

# Application imports
from src.model_clients import get_gemini_client, get_groq_client

logger = logging.getLogger(__name__)

def ask(client, model1, prompt) :
    """Send a prompt to an AI model and return its response text.

    Args:
        client: Initialized API client for the model provider.
        model: Model identifier
        prompt: User's question or instruction.

    Returns:
        The response text generated by the model.

    Raises:
        API-related exceptions if the request fails.
    """
    logger.info("Sending request to model=%s", model1)

    try : 

        response = client.chat.completions.create( 
            model=model1,  
            messages=[  
                {"role" : "user", "content": prompt}
            ]
        )
        return response.choices[0].message.content

    except Exception:
        logger.exception("Model request failed | model=%s", model1)
        raise

def battle(prompt) :
    """ Query two different AI models with the same prompt.

        Returns:
            A tuple containing the gemini model response followed by
            the groq response.
   """

    logger.info("Starting model comparison.")    
    response1 = ask (get_gemini_client(), os.getenv("GEMINI_MODEL"), prompt)
    response2 = ask (get_groq_client(), os.getenv("GROQ_MODEL"), prompt)
    logger.info("Starting model comparison.")

    return response1, response2

